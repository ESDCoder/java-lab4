package xyz.esdcoder.lab4;

import javafx.application.Application;

/**
 * Launcher class for the Parallelogram Calculator application.
 * Provides the main entry point for starting the JavaFX application.
 */
public class Launcher {
    /**
     * Main entry point for the application.
     *
     * @param args Command line arguments.
     */
    public static void main(String[] args) {
        Application.launch(ParallelogramApplication.class, args);
    }
}